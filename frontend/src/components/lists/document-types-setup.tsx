'use client'

/*
 * "How each document is made" (2026-11-17) : UNE seule place par type de document, pour Admin RH (avant : 3 endroits,
 * l'utilisatrice était perdue). Un clic sur "Set up" ouvre un panneau :
 *   - Comment est-il fait ? (•) Préparé par les RH (ils déposent le PDF signé)
 *                           ( ) Généré par l'application à partir de CE texte (codes {{ nom }}...) + Aperçu ;
 *   - ☐ Les RH relisent le texte avant l'envoi (pour compléter, ex. le salaire) ;
 *   - Avancé (facultatif) : un modèle Word que les RH téléchargent rempli (publipostage).
 * API : PATCH /api/documents/types/<id>/setup/, POST preview-model/, GET / POST / DELETE model/.
 */
import { useEffect, useState } from 'react'
import { Bot, Eye, FileText, Loader2, Settings2, Upload, UserRound } from 'lucide-react'
import { apiFetch } from '@/lib/api'
import type { DocumentType } from '@/lib/documents'
import { getFile } from '@/lib/expenses'
import { cn } from '@/lib/utils'
import { sendChange } from '@/lib/workflows'
import { actionClass } from '@/components/expenses/claim-actions'
import { SidePanel } from '@/components/ui/side-panel'

export function DocumentTypesSetup({ codes }: { codes: Record<string, string> }) {
  const [types, setTypes] = useState<DocumentType[] | null>(null)
  const [open, setOpen] = useState<DocumentType | null>(null)

  useEffect(() => {
    apiFetch('/api/documents/types/')
      .then(async (response) => { if (response.ok) setTypes(await response.json()) })
      .catch(() => setTypes([]))
  }, [])

  const replace = (updated: DocumentType) => setTypes((old) => old && old.map((item) => (item.id === updated.id ? updated : item)))

  return <fieldset>
    <legend className="text-xs font-semibold text-slate-700">How each document is made</legend>
    <p className="text-[11px] text-slate-500">Generated by the app (a PDF from your text, filled with the employee&apos;s data), or prepared by HR.</p>
    {types === null
      ? <p className="mt-2 text-[11px] text-slate-400">Loading...</p>
      : <ul className="mt-1.5 divide-y divide-slate-100 rounded-lg border border-slate-200">
          {types.map((type) => <li key={type.id} className="flex flex-wrap items-center gap-2 px-3 py-2 text-xs">
            {type.automatic ? <Bot className="size-4 shrink-0 text-emerald-600" aria-hidden /> : <UserRound className="size-4 shrink-0 text-slate-400" aria-hidden />}
            <span className="min-w-0 flex-1">
              <span className="block font-semibold text-[#192646]">{type.name}</span>
              <span className={cn('block text-[11px]', type.automatic ? 'text-emerald-700' : 'text-slate-500')}>
                {type.automatic ? `Generated by the app${type.hr_review ? ' · HR read it before sending' : ''}` : 'Prepared by HR'}
                {type.has_model ? ' · Word model' : ''}
              </span>
            </span>
            <button type="button" onClick={() => setOpen(type)} className={actionClass}><Settings2 className="size-3.5" /> Set up</button>
          </li>)}
        </ul>}
    <SidePanel open={open !== null} onClose={() => setOpen(null)} width={720} title={open ? open.name : ''}
      description="How is this document made?">
      {open && <SetupForm key={open.id} type={open} codes={codes} onSaved={(updated) => { replace(updated); setOpen(null) }}
        onModelChanged={(updated) => { replace(updated); setOpen(updated) }} />}
    </SidePanel>
  </fieldset>
}

function SetupForm({ type, codes, onSaved, onModelChanged }: {
  type: DocumentType; codes: Record<string, string>; onSaved: (updated: DocumentType) => void; onModelChanged: (updated: DocumentType) => void
}) {
  const work = type.template === 'WORK'  // l'attestation de travail : un texte prévu par l'application (texte vide = lui)
  const [generated, setGenerated] = useState(type.automatic)
  const [text, setText] = useState(type.body_template)
  const [review, setReview] = useState(type.hr_review)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')

  async function save() {
    setBusy(true)
    setError('')
    const result = await sendChange<DocumentType>(() => apiFetch(`/api/documents/types/${type.id}/setup/`,
      { method: 'PATCH', body: JSON.stringify({ generated, body_template: text, hr_review: review }) }), 'Only Admin RH can change this.')
    setBusy(false)
    if ('error' in result) return setError(result.error)
    onSaved(result.data)
  }

  // L'aperçu : l'onglet s'ouvre PENDANT le clic (sinon le navigateur le bloque), puis reçoit le PDF d'exemple.
  async function preview() {
    const tab = window.open('', '_blank')
    const response = await apiFetch(`/api/documents/types/${type.id}/preview-model/`, { method: 'POST', body: JSON.stringify({ text }) }).catch(() => null)
    if (!response?.ok) { tab?.close(); return setError('Could not build the preview.') }
    if (tab) tab.location.href = URL.createObjectURL(await response.blob())
  }

  const choices = [
    { value: false, icon: UserRound, title: 'Prepared by HR', text: 'HR prepare it in their tool, sign it, then upload the PDF and / or hand over the original.' },
    { value: true, icon: Bot, title: 'Generated by the app', text: 'A PDF made from the text below, filled with the employee\'s data, with the company header and signature.' },
  ]

  return <div className="flex flex-col gap-4">
    <div className="grid gap-2 sm:grid-cols-2">
      {choices.map((choice) => {
        const selected = generated === choice.value
        const Icon = choice.icon
        return <label key={choice.title} className={cn('flex cursor-pointer gap-2.5 rounded-xl border p-3',
          selected ? 'border-[#23355d] bg-[#E4E9F2]/50 ring-1 ring-[#23355d]' : 'border-slate-200 hover:border-slate-300')}>
          <input type="radio" name="made-by" checked={selected} onChange={() => { setGenerated(choice.value); setError('') }} className="mt-0.5 accent-[#192646]" />
          <span>
            <span className="flex items-center gap-1.5 text-sm font-semibold text-[#192646]"><Icon className="size-4" /> {choice.title}</span>
            <span className="mt-0.5 block text-[11px] leading-snug text-slate-500">{choice.text}</span>
          </span>
        </label>
      })}
    </div>

    {generated && <section className="flex flex-col gap-2">
      <label htmlFor="setup-text" className="text-xs font-semibold text-slate-700">Text of the document</label>
      <textarea id="setup-text" value={text} onChange={(event) => { setText(event.target.value); setError('') }} rows={10} maxLength={5000}
        placeholder={work ? 'Empty: the text provided by the app (it agrees with Madame / Monsieur and former employees).'
          : 'e.g. Nous soussignés, **{{ societe }}**, attestons que {{ civilite }} **{{ nom }} {{ prenom }}**, titulaire de la CIN n° {{ cin }}, ...'}
        className="w-full rounded-lg border border-slate-200 bg-white px-3 py-2 text-sm leading-relaxed outline-none focus:border-[#23355d] focus:ring-3 focus:ring-[#23355d]/15" />
      <div className="flex flex-wrap items-center gap-2">
        <p className="mr-auto text-[11px] text-slate-500">Blank line = new paragraph · **word** = bold · the codes below are replaced by the employee&apos;s data.</p>
        <button type="button" onClick={preview} className={actionClass}><Eye className="size-3.5" /> Preview</button>
      </div>
      <Codes codes={codes} />
      <label className="flex cursor-pointer items-start gap-2 rounded-lg border border-slate-200 px-3 py-2 text-xs">
        <input type="checkbox" checked={review} onChange={(event) => setReview(event.target.checked)} className="mt-0.5 accent-[#192646]" />
        <span><span className="font-semibold text-[#192646]">HR read the text before it is sent</span>
          <span className="block text-[11px] text-slate-500">To complete something the app does not know (e.g. the salary). Otherwise it is made as soon as HR approve.</span></span>
      </label>
    </section>}

    {!generated && <WordModel type={type} codes={codes} onChanged={onModelChanged} />}

    <div className="flex flex-wrap items-center justify-end gap-2 border-t border-slate-100 pt-3">
      {error && <p role="alert" className="mr-auto text-xs font-medium text-red-600">{error}</p>}
      <button type="button" disabled={busy} onClick={save}
        className="flex items-center gap-1.5 rounded-lg bg-[#23355d] px-4 py-2 text-xs font-semibold text-white hover:bg-[#192646] disabled:opacity-50">
        {busy && <Loader2 className="size-3.5 animate-spin" />} Save
      </button>
    </div>
  </div>
}

function Codes({ codes }: { codes: Record<string, string> }) {
  return <details className="rounded-lg bg-slate-50 px-3 py-2 text-[11px] text-slate-600">
    <summary className="cursor-pointer font-semibold text-[#23355d]">Codes you can use ({Object.keys(codes).length})</summary>
    <ul className="mt-1.5 grid gap-x-4 gap-y-0.5 sm:grid-cols-2">
      {Object.entries(codes).map(([code, meaning]) => <li key={code}>
        <code className="rounded bg-white px-1 font-semibold text-[#192646]">{`{{ ${code} }}`}</code> {meaning}
      </li>)}
    </ul>
  </details>
}

/** Avancé (facultatif) : un modèle Word que les RH téléchargent rempli (les mêmes codes), pour un document prépare par
 *  les RH avec une mise en page complexe. Enregistré tout de suite (sans le bouton Save). */
function WordModel({ type, codes, onChanged }: { type: DocumentType; codes: Record<string, string>; onChanged: (updated: DocumentType) => void }) {
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')

  async function change(file: File | null) {
    setBusy(true)
    setError('')
    const body = new FormData()
    if (file) body.append('file', file)
    const result = await sendChange<DocumentType>(() => apiFetch(`/api/documents/types/${type.id}/model/`,
      file ? { method: 'POST', body } : { method: 'DELETE' }), 'Only Admin RH can change the models.')
    setBusy(false)
    if ('error' in result) return setError(result.error)
    onChanged(result.data)
  }

  return <details className="rounded-lg border border-slate-200 px-3 py-2 text-xs" open={type.has_model}>
    <summary className="cursor-pointer font-semibold text-slate-700">Advanced (optional): a Word model for HR</summary>
    <p className="mt-1 text-[11px] text-slate-500">HR download it already filled (the same codes), check it, print it, sign it. Word (.docx) is filled; .doc, .odt, .pdf are given as they are.</p>
    <div className="mt-2 flex flex-wrap items-center gap-2">
      <FileText className="size-4 text-slate-400" aria-hidden />
      <span className={cn('min-w-0 flex-1 truncate', type.has_model ? 'text-emerald-700' : 'text-slate-400')}>{type.has_model ? type.model_name : 'No Word model'}</span>
      {busy && <Loader2 className="size-3.5 animate-spin text-slate-400" />}
      {type.has_model && <button type="button" className={actionClass}
        onClick={async () => setError(await getFile(`/api/documents/types/${type.id}/model/`, type.model_name, true))}>Download</button>}
      <label className={cn(actionClass, 'cursor-pointer')}>
        <Upload className="size-3.5" /> {type.has_model ? 'Replace' : 'Upload'}
        <input type="file" accept=".docx,.doc,.odt,.pdf" className="sr-only"
          onChange={(event) => { change(event.target.files?.[0] ?? null); event.target.value = '' }} />
      </label>
      {type.has_model && <button type="button" onClick={() => change(null)} className={cn(actionClass, 'text-red-600 hover:bg-red-50')}>Remove</button>}
    </div>
    <div className="mt-2"><Codes codes={codes} /></div>
    {error && <p role="alert" className="mt-1.5 text-[11px] font-medium text-red-600">{error}</p>}
  </details>
}
