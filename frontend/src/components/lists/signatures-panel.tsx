'use client'

/*
 * "Signatures" (Reference lists -> Documents), Admin RH et IT (2026-11-13, standard Workday / SAP) : pour chaque
 * pôle, QUI signe les documents générés par l'application (l'attestation de travail) et COMMENT :
 * - "Sign by hand" : le PDF garde une place vide ; les RH impriment, signent et tamponnent ;
 * - "Signature & stamp added by the app" : les images (données UNE fois) sont posées sur chaque PDF, seulement
 *   après la validation des RH. Il faut l'accord du signataire pour utiliser sa signature.
 * "Preview" montre une attestation d'exemple avec le réglage enregistré. Lu et enregistré dans /api/documents/signatories/.
 */
import { useEffect, useRef, useState, type FormEvent } from 'react'
import { CheckCircle2, Eye, ImagePlus, Loader2, PenLine, Stamp, Trash2 } from 'lucide-react'
import { apiFetch } from '@/lib/api'
import { getFile } from '@/lib/expenses'
import { formatDateTime } from '@/components/employees/history-changes'
import { controlClass } from '@/components/employees/form-fields'
import { cn } from '@/lib/utils'
import { sendChange } from '@/lib/workflows'

type Signatory = {
  id: number; pole: string; name: string; title: string; city: string; mode: 'HAND' | 'IMAGE'
  has_signature: boolean; has_stamp: boolean; updated_at: string; updated_by: string | null
}

export function SignaturesPanel() {
  const [signatories, setSignatories] = useState<Signatory[] | null>(null)
  const [failed, setFailed] = useState(false)

  useEffect(() => {
    apiFetch('/api/documents/signatories/')
      .then(async (response) => {
        if (!response.ok) throw new Error()
        setSignatories(await response.json())
      })
      .catch(() => setFailed(true))
  }, [])

  return <section className="flex min-w-0 flex-col gap-4">
    <div className="rounded-xl border border-slate-200/80 bg-white px-4 py-3 shadow-[0_1px_2px_rgba(15,23,42,0.04)]">
      <h2 className="text-sm font-semibold text-[#192646]">Signatures</h2>
      <p className="text-[11px] text-slate-500">Who signs the documents generated by the app (work certificate), and how. One setting per pôle.
        Documents already delivered do not change.</p>
    </div>
    {signatories === null
      ? <p className="rounded-xl border border-slate-200 bg-white px-4 py-10 text-center text-sm text-slate-500">
          {failed ? 'Could not load the signatures (Admin RH only).' : 'Loading...'}
        </p>
      : signatories.map((signatory) => <SignatoryCard key={signatory.id} initial={signatory} />)}
  </section>
}

const MODES = [
  { id: 'HAND' as const, icon: PenLine, title: 'Sign by hand',
    text: 'The app prepares a draft for HR only. HR print it, sign and stamp it, then upload the scan: the employee never gets an unsigned document.' },
  { id: 'IMAGE' as const, icon: Stamp, title: 'Signature & stamp added by the app',
    text: 'Upload them once: they are added to every certificate, only after HR approval. Needs the signatory\'s agreement.' },
]

function SignatoryCard({ initial }: { initial: Signatory }) {
  const [saved, setSaved] = useState(initial)
  const [draft, setDraft] = useState({ name: initial.name, title: initial.title, city: initial.city, mode: initial.mode })
  const [files, setFiles] = useState<{ signature?: File | null; stamp?: File | null }>({})  // null : à enlever
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')
  const [done, setDone] = useState(false)
  const [version, setVersion] = useState(0)  // +1 après un enregistrement : les images sont relues

  const changed = draft.name !== saved.name || draft.title !== saved.title || draft.city !== saved.city
    || draft.mode !== saved.mode || files.signature !== undefined || files.stamp !== undefined

  async function save(event: FormEvent) {
    event.preventDefault()
    setBusy(true)
    setError('')
    const form = new FormData()
    Object.entries(draft).forEach(([key, value]) => form.append(key, value))
    for (const kind of ['signature', 'stamp'] as const) {
      if (files[kind]) form.append(kind, files[kind] as File)
      else if (files[kind] === null) form.append(`remove_${kind}`, 'true')
    }
    const result = await sendChange<Signatory>(() => apiFetch(`/api/documents/signatories/${saved.id}/`, { method: 'PATCH', body: form }),
      'Only Admin RH can change the signatures.')
    setBusy(false)
    if ('error' in result) return setError(result.error)
    setSaved(result.data)
    setFiles({})
    setVersion((old) => old + 1)
    setDone(true)
  }

  const set = (field: keyof typeof draft) => (value: string) => { setDraft((old) => ({ ...old, [field]: value })); setDone(false) }

  return <form onSubmit={save} className="rounded-xl border border-slate-200/80 bg-white shadow-[0_1px_2px_rgba(15,23,42,0.04)]">
    <header className="flex flex-wrap items-center gap-2 border-b border-slate-100 px-4 py-3">
      <h3 className="text-sm font-semibold text-[#192646]">{saved.pole}</h3>
      <span className="text-[11px] text-slate-400">
        Updated {formatDateTime(saved.updated_at)}{saved.updated_by ? ` by ${saved.updated_by}` : ''}
      </span>
      <button type="button" onClick={() => getFile(`/api/documents/signatories/${saved.id}/preview/`, `exemple-${saved.pole}.pdf`, false)}
        className="ml-auto flex items-center gap-1 rounded-md px-2 py-1 text-[11px] font-semibold text-[#23355d] hover:bg-slate-100"
        title="An example certificate with the SAVED setting">
        <Eye className="size-3.5" /> Preview
      </button>
    </header>

    <div className="grid gap-3 px-4 py-4 sm:grid-cols-3">
      <TextInput id={`name-${saved.id}`} label="Signatory name" value={draft.name} onChange={set('name')} placeholder="e.g. Karima Idrissi (optional)" />
      <TextInput id={`title-${saved.id}`} label="Title" value={draft.title} onChange={set('title')} placeholder="Le Directeur des Ressources Humaines" />
      <TextInput id={`city-${saved.id}`} label="City (« Fait à »)" value={draft.city} onChange={set('city')} placeholder="Casablanca" />
    </div>

    {/* Comment signer : deux cartes à choisir (comme des boutons radio). */}
    <fieldset className="grid gap-2 px-4 pb-4 sm:grid-cols-2">
      <legend className="mb-1.5 text-xs font-semibold text-slate-700">How the certificate is signed</legend>
      {MODES.map(({ id, icon: Icon, title, text }) => {
        const selected = draft.mode === id
        return <label key={id} className={cn('flex cursor-pointer gap-3 rounded-lg border p-3 transition-colors',
          selected ? 'border-[#23355d] bg-[#E4E9F2]/50 ring-1 ring-[#23355d]' : 'border-slate-200 hover:border-slate-300')}>
          <input type="radio" name={`mode-${saved.id}`} value={id} checked={selected} onChange={() => set('mode')(id)} className="mt-0.5 accent-[#192646]" />
          <span>
            <span className="flex items-center gap-1.5 text-xs font-semibold text-[#192646]"><Icon className="size-3.5" aria-hidden /> {title}</span>
            <span className="mt-0.5 block text-[11px] text-slate-500">{text}</span>
          </span>
        </label>
      })}
    </fieldset>

    {draft.mode === 'IMAGE' && <div className="grid gap-3 border-t border-slate-100 px-4 py-4 sm:grid-cols-2">
      <ImageSlot label="Signature (required)" kind="signature" signatory={saved} version={version} file={files.signature}
        onChange={(file) => { setFiles((old) => ({ ...old, signature: file })); setDone(false) }} />
      <ImageSlot label="Company stamp" kind="stamp" signatory={saved} version={version} file={files.stamp}
        onChange={(file) => { setFiles((old) => ({ ...old, stamp: file })); setDone(false) }} />
      <p className="text-[11px] text-slate-500 sm:col-span-2">PNG or JPG, 1 MB max. A PNG with a transparent background looks best on the certificate.</p>
    </div>}

    <footer className="flex flex-wrap items-center justify-end gap-2 border-t border-slate-100 px-4 py-3">
      {error && <p role="alert" className="mr-auto text-[11px] font-medium text-red-600">{error}</p>}
      {done && !changed && <p role="status" className="mr-auto flex items-center gap-1 text-[11px] font-medium text-emerald-700">
        <CheckCircle2 className="size-3.5" /> Saved. New certificates use this setting.
      </p>}
      <button type="submit" disabled={busy || !changed}
        className="flex items-center gap-1.5 rounded-lg bg-[#23355d] px-4 py-2 text-xs font-semibold text-white hover:bg-[#192646] disabled:opacity-50">
        {busy && <Loader2 className="size-3.5 animate-spin" />} Save
      </button>
    </footer>
  </form>
}

function TextInput({ id, label, value, onChange, placeholder }: { id: string; label: string; value: string; onChange: (value: string) => void; placeholder: string }) {
  return <div>
    <label htmlFor={id} className="block text-xs font-semibold text-slate-700">{label}</label>
    <input id={id} value={value} onChange={(e) => onChange(e.target.value)} placeholder={placeholder} maxLength={150} className={controlClass} />
  </div>
}

/** Une image (signature ou cachet) : l'aperçu, "Choose" et "Remove". file : undefined = inchangée, null = à enlever. */
function ImageSlot({ label, kind, signatory, version, file, onChange }: {
  label: string; kind: 'signature' | 'stamp'; signatory: Signatory; version: number
  file: File | null | undefined; onChange: (file: File | null | undefined) => void
}) {
  const input = useRef<HTMLInputElement>(null)
  const [stored, setStored] = useState<string | null>(null)  // l'image enregistrée (lue avec les cookies)
  const exists = kind === 'signature' ? signatory.has_signature : signatory.has_stamp

  useEffect(() => {
    if (!exists) return
    let url: string | null = null
    apiFetch(`/api/documents/signatories/${signatory.id}/image/?kind=${kind}`)
      .then(async (response) => {
        if (!response.ok) return
        url = URL.createObjectURL(await response.blob())
        setStored(url)
      })
      .catch(() => { /* l'image ne s'affiche pas : le reste de la page marche */ })
    return () => { if (url) URL.revokeObjectURL(url) }
  }, [exists, kind, signatory.id, version])

  // Ce qu'on montre : le nouveau fichier choisi, sinon l'image enregistrée (sauf si on vient de l'enlever).
  const [chosen, setChosen] = useState<string | null>(null)
  const shown = file ? chosen : file === null || !exists ? null : stored

  function pick(picked: File | undefined) {
    if (!picked) return
    if (chosen) URL.revokeObjectURL(chosen)  // l'aperçu d'avant n'est plus utile
    setChosen(URL.createObjectURL(picked))
    onChange(picked)
  }

  return <div>
    <p className="text-xs font-semibold text-slate-700">{label}</p>
    <div className="mt-1.5 flex items-center gap-3 rounded-lg border border-dashed border-slate-300 bg-slate-50 p-3">
      <div className="flex h-16 w-28 shrink-0 items-center justify-center rounded-md bg-white ring-1 ring-slate-200">
        {shown
          ? <img src={shown} alt={label} className="max-h-14 max-w-24 object-contain" />  // eslint-disable-line @next/next/no-img-element
          : <ImagePlus className="size-5 text-slate-300" aria-hidden />}
      </div>
      <div className="flex flex-col items-start gap-1">
        <input ref={input} type="file" accept="image/png,image/jpeg" className="sr-only" aria-label={label}
          onChange={(event) => { pick(event.target.files?.[0]); event.target.value = '' }} />
        <button type="button" onClick={() => input.current?.click()} className="rounded-md px-2 py-1 text-[11px] font-semibold text-[#23355d] hover:bg-white">
          {shown ? 'Replace' : 'Choose an image'}
        </button>
        {shown && <button type="button" onClick={() => onChange(null)} className="flex items-center gap-1 rounded-md px-2 py-1 text-[11px] font-semibold text-red-600 hover:bg-red-50">
          <Trash2 className="size-3" /> Remove
        </button>}
      </div>
    </div>
  </div>
}
